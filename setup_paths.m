% setup_paths.m — add all src/ and demos/ trees to the Octave load path.
%
% Run once at the start of every session:
%   octave-cli --no-gui --quiet --eval "run('setup_paths.m');"
%
% This keeps every .m file self-contained (one public primary function per
% file matching its filename) while giving Octave a flat search path so any
% demo can call any core/domain/tool module by its bare function name.

this_file = mfilename("fullpath");
this_dir  = fileparts(this_file);

roots = { ...
  fullfile(this_dir, "src", "core"), ...
  fullfile(this_dir, "src", "domains", "ground_vehicles"), ...
  fullfile(this_dir, "src", "domains", "manipulation"), ...
  fullfile(this_dir, "src", "domains", "legged_locomotion"), ...
  fullfile(this_dir, "src", "domains", "robot_modeling"), ...
  fullfile(this_dir, "src", "domains", "perception"), ...
  fullfile(this_dir, "src", "domains", "mapping_slam"), ...
  fullfile(this_dir, "src", "domains", "motion_planning"), ...
  fullfile(this_dir, "src", "domains", "motion_control"), ...
  fullfile(this_dir, "src", "domains", "uav"), ...
  fullfile(this_dir, "src", "domains", "marine_auv"), ...
  fullfile(this_dir, "src", "domains", "automated_driving"), ...
  fullfile(this_dir, "src", "tools", "simulators"), ...
  fullfile(this_dir, "src", "tools", "ros_middleware"), ...
  fullfile(this_dir, "src", "tools", "hardware_connectivity"), ...
  fullfile(this_dir, "demos"), ...
  fullfile(this_dir, "tests") ...
};

for i = 1:numel(roots)
  addpath(genpath(roots{i}));
endfor

disp(sprintf("setup_paths: added %d source/demo/test roots", numel(roots)));
